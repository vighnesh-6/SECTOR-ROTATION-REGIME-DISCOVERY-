"""
Phase 10.6 Investigation 1 — Transaction Cost Sensitivity & Breakeven Analysis.

Evaluates portfolio return erosion and friction dynamics across 0 to 30 bps one-way turnover
(0, 5, 10, 15 [baseline], 20, 25, 30 bps) for all four canonical strategies (1A, 1B, 2A, 2B)
across Training, Previously Examined Out-of-Sample Holdout, and Full Cycle evaluation windows.
"""

import logging
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union

import numpy as np
import pandas as pd

from src.comparative_evaluation import compute_single_portfolio_metrics
from src.portfolio_backtest import VARIANTS, simulate_portfolio

logger = logging.getLogger(__name__)

# Canonical cost rates in basis points
DEFAULT_COST_BPS_GRID: List[int] = [0, 5, 10, 15, 20, 25, 30]

PERIOD_RANGES: Dict[str, Tuple[str, str]] = {
    "train": ("2019-11-01", "2024-12-31"),
    "holdout": ("2025-01-02", "2026-09-18"),
    "full": ("2019-11-01", "2026-09-18"),
}


def run_cost_sensitivity_analysis(
    schedules: Dict[str, pd.DataFrame],
    price_df: pd.DataFrame,
    cost_bps_grid: Optional[List[int]] = None,
    variants: Optional[List[str]] = None,
    output_dir: Optional[Union[str, Path]] = None,
) -> pd.DataFrame:
    """
    Execute transaction cost sensitivity sweeps across strategies, cost rates, and periods.

    Args:
      schedules: Dictionary of Phase 9 target-weight schedules for variants (1A, 1B, 2A, 2B).
      price_df: Aligned prices DataFrame covering evaluation timeline.
      cost_bps_grid: List of cost rates in basis points (default: [0, 5, 10, 15, 20, 25, 30]).
      variants: List of strategy variants to evaluate (default: ['1A', '1B', '2A', '2B']).
      output_dir: Optional directory to save Parquet output.

    Returns:
      pd.DataFrame: 84-row DataFrame with performance and friction metrics across scenarios.
    """
    grid = cost_bps_grid if cost_bps_grid is not None else DEFAULT_COST_BPS_GRID
    vars_to_run = variants if variants is not None else VARIANTS

    records: List[Dict[str, Any]] = []

    for v in vars_to_run:
        schedule_v = schedules[v]
        for bps in grid:
            cost_rate = bps / 10000.0
            daily_df = simulate_portfolio(
                schedule_df=schedule_v,
                price_df=price_df,
                cost_rate=cost_rate,
            )

            # Evaluate across train, holdout, full periods
            for period_name in ["train", "holdout", "full"]:
                m = compute_single_portfolio_metrics(
                    daily_df=daily_df,
                    period=period_name,
                    portfolio_key=v,
                )

                rec = {
                    "strategy": v,
                    "period": period_name,
                    "cost_bps": int(bps),
                    "cost_rate": float(cost_rate),
                    "sample_count": int(m["sample_count"]),
                    "gross_total_return": float(m["total_return_gross_pct"] / 100.0),
                    "net_total_return": float(m["total_return_net_pct"] / 100.0),
                    "gross_cagr": float(m["cagr_gross_pct"] / 100.0),
                    "net_cagr": float(m["cagr_net_pct"] / 100.0),
                    "cost_drag": float(m["cagr_cost_drag_pct"] / 100.0),
                    "annualized_vol": float(m["ann_volatility_pct"] / 100.0),
                    "sharpe_ratio": float(m["sharpe_ratio"]),
                    "sortino_ratio": float(m["sortino_ratio"]),
                    "max_drawdown": float(m["max_drawdown_pct"] / 100.0),
                    "cash_costs_paid": float(m["cum_transaction_costs"]),
                    "actual_turnover_cumulative": float(m["cum_actual_turnover"]),
                    "actual_turnover_annualized": float(m["ann_actual_turnover"]),
                }
                records.append(rec)

    results_df = pd.DataFrame(records)

    if output_dir is not None:
        out_path = Path(output_dir) / "cost_sensitivity.parquet"
        out_path.parent.mkdir(parents=True, exist_ok=True)
        results_df.to_parquet(out_path, index=False)
        logger.info(f"Saved Investigation 1 Parquet to: {out_path}")

    return results_df


def compute_breakeven_cost_rates(
    cost_df: pd.DataFrame,
    benchmark_cagrs: Optional[Dict[str, Dict[str, float]]] = None,
) -> pd.DataFrame:
    """
    Compute breakeven transaction cost rates where Net CAGR drops to 0.0%, NIFTY 50 CAGR,
    or Equal-Weight 6S CAGR via linear interpolation / extrapolation across the cost grid.

    Args:
      cost_df: DataFrame generated by run_cost_sensitivity_analysis.
      benchmark_cagrs: Optional dict mapping benchmark name ('NIFTY50', 'EQUAL_WEIGHT')
                       to dict of period -> Net CAGR.

    Returns:
      pd.DataFrame: Table of breakeven cost rates in bps per strategy and period.
    """
    def _solve_breakeven(bps: np.ndarray, cagrs: np.ndarray, target: float) -> float:
        # Check for bracket within grid
        for i in range(len(cagrs) - 1):
            y0, y1 = cagrs[i], cagrs[i + 1]
            x0, x1 = bps[i], bps[i + 1]
            if (y0 >= target >= y1) or (y0 <= target <= y1):
                if y0 != y1:
                    return float(x0 + (target - y0) * (x1 - x0) / (y1 - y0))
                return float(x0)

        # Linear extrapolation from grid endpoints
        x0, x1 = bps[0], bps[-1]
        y0, y1 = cagrs[0], cagrs[-1]
        if y1 != y0:
            return float(x0 + (target - y0) * (x1 - x0) / (y1 - y0))
        return np.nan

    records: List[Dict[str, Any]] = []

    for (strat, period), grp in cost_df.groupby(["strategy", "period"]):
        sorted_grp = grp.sort_values("cost_bps")
        bps_arr = sorted_grp["cost_bps"].values.astype(float)
        cagr_arr = sorted_grp["net_cagr"].values.astype(float)

        be_zero = _solve_breakeven(bps_arr, cagr_arr, 0.0)

        rec = {
            "strategy": strat,
            "period": period,
            "breakeven_zero_cagr_bps": float(be_zero) if pd.notna(be_zero) else np.nan,
        }

        # Benchmark hurdles if supplied
        if benchmark_cagrs is not None:
            for bm_name, bm_dict in benchmark_cagrs.items():
                bm_cagr = bm_dict.get(period, np.nan)
                be_bm = _solve_breakeven(bps_arr, cagr_arr, bm_cagr) if pd.notna(bm_cagr) else np.nan
                rec[f"breakeven_vs_{bm_name.lower()}_bps"] = float(be_bm) if pd.notna(be_bm) else np.nan

        records.append(rec)

    return pd.DataFrame(records)
